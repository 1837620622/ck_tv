const INV_SBOX = new Uint8Array(256);
for (let index = 0; index < 256; index += 1) INV_SBOX[SBOX[index]] = index;

const RCON = [0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36];

function xtime(value: number): number {
  return ((value << 1) ^ ((value >> 7) * 0x1b)) & 0xff;
}

function mul(left: number, right: number): number {
  let result = 0;
  let a = left;
  let b = right;
  for (let bit = 0; bit < 8; bit += 1) {
    if (b & 1) result ^= a;
    a = xtime(a);
    b >>= 1;
  }
  return result;
}

function expandKey(key: Uint8Array): Uint8Array {
  const words = new Uint8Array(176);
  words.set(key.subarray(0, 16));
  let offset = 16;
  let rconIndex = 1;
  const temp = new Uint8Array(4);
  while (offset < 176) {
    temp.set(words.subarray(offset - 4, offset));
    if (offset % 16 === 0) {
      const first = temp[0];
      temp[0] = SBOX[temp[1]] ^ RCON[rconIndex];
      temp[1] = SBOX[temp[2]];
      temp[2] = SBOX[temp[3]];
      temp[3] = SBOX[first];
      rconIndex += 1;
    }
    for (let index = 0; index < 4; index += 1) {
      words[offset] = words[offset - 16] ^ temp[index];
      offset += 1;
    }
  }
  return words;
}

function addRoundKey(state: Uint8Array, words: Uint8Array, round: number) {
  const start = round * 16;
  for (let index = 0; index < 16; index += 1)
    state[index] ^= words[start + index];
}

function invShiftRows(state: Uint8Array) {
  const next = state.slice();
  next[1] = state[13];
  next[5] = state[1];
  next[9] = state[5];
  next[13] = state[9];
  next[2] = state[10];
  next[6] = state[14];
  next[10] = state[2];
  next[14] = state[6];
  next[3] = state[7];
  next[7] = state[11];
  next[11] = state[15];
  next[15] = state[3];
  state.set(next);
}

function invSubBytes(state: Uint8Array) {
  for (let index = 0; index < 16; index += 1)
    state[index] = INV_SBOX[state[index]];
}

function invMixColumns(state: Uint8Array) {
  for (let column = 0; column < 4; column += 1) {
    const offset = column * 4;
    const a = state[offset];
    const b = state[offset + 1];
    const c = state[offset + 2];
    const d = state[offset + 3];
    state[offset] = mul(a, 0x0e) ^ mul(b, 0x0b) ^ mul(c, 0x0d) ^ mul(d, 0x09);
    state[offset + 1] =
      mul(a, 0x09) ^ mul(b, 0x0e) ^ mul(c, 0x0b) ^ mul(d, 0x0d);
    state[offset + 2] =
      mul(a, 0x0d) ^ mul(b, 0x09) ^ mul(c, 0x0e) ^ mul(d, 0x0b);
    state[offset + 3] =
      mul(a, 0x0b) ^ mul(b, 0x0d) ^ mul(c, 0x09) ^ mul(d, 0x0e);
  }
}

function decryptBlock(block: Uint8Array, words: Uint8Array): Uint8Array {
  // Buffer.slice 会共享内存，必须拷贝成普通 Uint8Array。
  const state = new Uint8Array(block);
  addRoundKey(state, words, 10);
  for (let round = 9; round >= 1; round -= 1) {
    invShiftRows(state);
    invSubBytes(state);
    addRoundKey(state, words, round);
    invMixColumns(state);
  }
  invShiftRows(state);
  invSubBytes(state);
  addRoundKey(state, words, 0);
  return state;
}

export function decryptAes128Cbc(
  data: Uint8Array,
  key: Uint8Array,
  iv: Uint8Array
): Uint8Array {
  if (key.length !== 16 || iv.length !== 16 || data.length % 16 !== 0) {
    return new Uint8Array();
  }
  const bytes = new Uint8Array(data);
  const words = expandKey(key);
  const output = new Uint8Array(bytes.length);
  let previous = new Uint8Array(iv);
  for (let offset = 0; offset < bytes.length; offset += 16) {
    const block = bytes.subarray(offset, offset + 16);
    const plain = decryptBlock(block, words);
    for (let index = 0; index < 16; index += 1) {
      output[offset + index] = plain[index] ^ previous[index];
    }
    previous = block.slice();
  }
  return output;
}
