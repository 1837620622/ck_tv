/* eslint-env jest */
/* eslint-disable @typescript-eslint/no-var-requires */
const {
  mergeHeaders,
  mergeRoutes,
  publicRules,
  MAX_RULES,
} = require('./pages-static');

const entry = (name, dir = false) => ({ name, isDirectory: () => dir });

describe('pages static routes', () => {
  it('turns public files and folders into exclude rules', () => {
    expect(
      publicRules([
        entry('logo.png'),
        entry('icons', true),
        entry('sw.js'),
        entry('.DS_Store'),
      ])
    ).toEqual(['/icons/*', '/logo.png', '/sw.js']);
  });

  it('keeps the generated rules and adds the new ones once', () => {
    const merged = mergeRoutes(
      { version: 1, include: ['/*'], exclude: ['/_next/static/*'] },
      ['/logo.png', '/_next/static/*', '/icons/*']
    );
    expect(merged).toEqual({
      version: 1,
      include: ['/*'],
      exclude: ['/_next/static/*', '/logo.png', '/icons/*'],
    });
  });

  it('stays inside the Pages limit of 100 rules', () => {
    const many = Array.from({ length: 200 }, (_, i) => `/f${i}.png`);
    const merged = mergeRoutes({ include: ['/*'], exclude: [] }, many);
    expect(merged.include.length + merged.exclude.length).toBe(MAX_RULES);
  });
});

describe('pages static headers', () => {
  const generated =
    '# === START AUTOGENERATED @cloudflare/next-on-pages IMMUTABLE HEADERS ===\n' +
    '/_next/static/*\n  cache-control: public,max-age=31536000,immutable\n' +
    '# === END AUTOGENERATED @cloudflare/next-on-pages IMMUTABLE HEADERS ===\n';

  it('appends cache rules after the generated block', () => {
    const out = mergeHeaders(generated);
    expect(out.startsWith(generated.trimEnd())).toBe(true);
    expect(out).toContain('/icons/*\n  cache-control: public, max-age=86400');
    expect(out).toContain('/sw.js\n  cache-control: no-cache');
  });

  it('replaces its own block instead of stacking it on a second run', () => {
    const twice = mergeHeaders(mergeHeaders(generated));
    expect(twice).toBe(mergeHeaders(generated));
  });
});
